BASE = "http://localhost:8002/api/v1"
ENV_PATH = Path(r"D:\software\code\ideas\list\aigc-studio\.env")


def env(k: str) -> str:
    for line in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith(k + "="):
            return line.split("=", 1)[1].strip()
    raise KeyError(k)


